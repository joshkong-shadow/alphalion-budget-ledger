#!/usr/bin/env node
/* Encrypted storage for the ledger, so the repo and its GitHub Pages site never hold readable spend data.

   node scripts/vault.mjs unpack   decrypt enc/state/** back into data/ (the scripts' working files)
   node scripts/vault.mjs pack     encrypt data/ into enc/state/** (only files whose content changed),
                                   bundle the page's documents into enc/docs.bin, write enc/last_run.json
   node scripts/vault.mjs due      print "yes" if today's (Pacific) refresh has not run yet, else "no"

   Passphrase: LEDGER_PASSPHRASE env var, or ~/.config/moby/budget-ledger-passphrase.
   Crypto: PBKDF2-SHA256 (300k) -> AES-256-GCM, gzip inside, salt in enc/salt.json (clear).
   The same passphrase is the page's password: the browser derives the same key to read enc/docs.bin. */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from 'node:fs';
import { gzipSync, gunzipSync } from 'node:zlib';
import { webcrypto as wc, randomBytes, createHmac } from 'node:crypto';
import { homedir } from 'node:os';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'data'), ENC = join(ROOT, 'enc'), STATE = join(ENC, 'state');
const CMD = process.argv[2];
const TZ = JSON.parse(readFileSync(join(ROOT, 'ledger.config.json'), 'utf8')).timezone || 'America/Los_Angeles';
const pacificDate = (d = new Date()) => new Intl.DateTimeFormat('en-CA', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);

if (CMD === 'due') {
  const f = join(ENC, 'last_run.json');
  const last = existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')).pacific_date : null;
  console.log(last === pacificDate() ? 'no' : 'yes');
  process.exit(0);
}

function passphrase() {
  if (process.env.LEDGER_PASSPHRASE) return process.env.LEDGER_PASSPHRASE.trim();
  const f = join(homedir(), '.config', 'moby', 'budget-ledger-passphrase');
  if (existsSync(f)) return readFileSync(f, 'utf8').trim();
  console.error('No passphrase: set LEDGER_PASSPHRASE or create ~/.config/moby/budget-ledger-passphrase'); process.exit(1);
}

mkdirSync(STATE, { recursive: true });
const saltFile = join(ENC, 'salt.json');
let salt;
if (existsSync(saltFile)) salt = Buffer.from(JSON.parse(readFileSync(saltFile, 'utf8')).salt, 'base64');
else { salt = randomBytes(16); writeFileSync(saltFile, JSON.stringify({ salt: salt.toString('base64'), kdf: 'PBKDF2-SHA256', iter: 300000 })); }

const pass = passphrase();
const key = await wc.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: 300000, hash: 'SHA-256' },
  await wc.subtle.importKey('raw', new TextEncoder().encode(pass), 'PBKDF2', false, ['deriveKey']),
  { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
// keyed fingerprint of each plaintext file, so unchanged files are not re-encrypted (no daily churn in git)
const finger = buf => createHmac('sha256', pass + ':' + salt.toString('base64')).update(buf).digest('hex');

async function seal(plain) {
  const iv = randomBytes(12);
  return Buffer.concat([iv, Buffer.from(await wc.subtle.encrypt({ name: 'AES-GCM', iv }, key, gzipSync(plain)))]);
}
async function open(buf) {
  return gunzipSync(Buffer.from(await wc.subtle.decrypt({ name: 'AES-GCM', iv: buf.subarray(0, 12) }, key, buf.subarray(12))));
}
const walk = dir => !existsSync(dir) ? [] : readdirSync(dir).flatMap(n => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; });

// what the build needs to carry from day to day; data/artifact/* is regenerated by every build
const KEEP = ['raw', 'snapshots', 'visits', 'budgetlog'];
const manifestFile = join(ENC, 'state-manifest.json');
const manifest = existsSync(manifestFile) ? JSON.parse(readFileSync(manifestFile, 'utf8')) : {};

if (CMD === 'unpack') {
  let n = 0;
  for (const f of walk(STATE).filter(f => f.endsWith('.bin'))) {
    const rel = relative(STATE, f).replace(/\.bin$/, '');
    const out = join(DATA, rel); mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, await open(readFileSync(f))); n++;
  }
  console.log(`unpacked ${n} files into data/`);
} else if (CMD === 'pack') {
  let changed = 0, total = 0;
  for (const sub of KEEP) for (const f of walk(join(DATA, sub))) {
    const rel = relative(DATA, f), buf = readFileSync(f), fp = finger(buf); total++;
    if (manifest[rel] === fp && existsSync(join(STATE, rel + '.bin'))) continue;
    const out = join(STATE, rel + '.bin'); mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, await seal(buf)); manifest[rel] = fp; changed++;
  }
  writeFileSync(manifestFile, JSON.stringify(manifest, null, 1));
  // the page's documents: one bundle, keyed "collection/doc_id", same shape the artifact database held
  const docsDir = join(DATA, 'artifact', 'docs');
  const docs = {};
  for (const f of walk(docsDir).filter(f => f.endsWith('.json'))) {
    const [collection, id] = relative(docsDir, f).replace(/\.json$/, '').split('__');
    docs[`${collection}/${id}`] = JSON.parse(readFileSync(f, 'utf8'));
  }
  if (!docs['budget/meta']) { console.error('pack: data/artifact/docs has no budget__meta.json — run build_ledger.mjs first'); process.exit(1); }
  const ranAt = new Date();
  writeFileSync(join(ENC, 'docs.bin'), await seal(Buffer.from(JSON.stringify({ refreshed_at: ranAt.toISOString(), docs }))));
  writeFileSync(join(ENC, 'last_run.json'), JSON.stringify({ pacific_date: pacificDate(ranAt), at: ranAt.toISOString() }));
  console.log(`packed: ${changed} of ${total} state files changed · ${Object.keys(docs).length} page documents bundled`);
} else {
  console.error('Usage: vault.mjs unpack | pack | due'); process.exit(1);
}
